#!/usr/bin/env python3
"""Generate color-dependent files from palette/elto-palette.json (stdlib only).
Outputs: aurorae/ElToClassic/*.svg + ElToClassicrc text colors, panel-widgets/ElToPalette.qml.
A target is skipped if its directory is not present in this checkout.
CONCEPT/SPIKE, UNVERIFIED."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = json.load(open(os.path.join(ROOT, "palette", "elto-palette.json")))
M = P.get("motion", {})
P = {k: v for k, v in P.items() if not k.startswith("_") and isinstance(v, str)}

def rgba(h):
    return ",".join(str(int(h[i:i+2], 16)) for i in (1, 3, 5)) + ",255"

def svg(body, w=30, h=20):
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">\n{body}</svg>\n'

def btn(bg, fg, hbg, glyph):
    c = P
    states = {"active": (bg, fg), "hover": (hbg, fg), "pressed": (c["green"], c["cream"]),
              "inactive": (c["inactiveBg"], c["inactiveFg"]), "hover-inactive": (hbg, fg),
              "pressed-inactive": (c["green"], c["cream"]),
              "deactivated": (c["inactiveBg"], c["inactiveFg"]),
              "deactivated-inactive": (c["inactiveBg"], c["inactiveFg"])}
    out = ""
    for s, (col, g) in states.items():
        out += f'<g id="{s}"><rect id="{s}-center" width="30" height="20" rx="10" fill="{col}"/>{glyph(g)}</g>\n'
    return svg(out)

def frame(prefix, top, bg, T=32, B=10, S=10):
    # soft frame: all four corners rounded (radius S), border S wide. Aurorae stretches each piece
    # to the border sizes in the rc, so keep S equal to BorderLeft/BorderRight/BorderBottom there.
    W = S * 2 + 20
    o = f'<g id="{prefix}">\n'
    def r(n, x, y, w, h, f): return f'<rect id="{prefix}-{n}" x="{x}" y="{y}" width="{w}" height="{h}" fill="{f}"/>\n'
    o += f'<path id="{prefix}-topleft" d="M0 {S}A{S} {S} 0 0 1 {S} 0V{T}H0Z" fill="{top}"/>\n'
    o += r("top", S, 0, 20, T, top)
    o += f'<path id="{prefix}-topright" d="M{S+20} 0A{S} {S} 0 0 1 {W} {S}V{T}H{S+20}Z" fill="{top}"/>\n'
    o += r("left", 0, T, S, 20, bg) + r("center", S, T, 20, 20, bg) + r("right", S+20, T, S, 20, bg)
    y = T + 20
    o += f'<path id="{prefix}-bottomleft" d="M0 {y}H{S}V{y+B}H{S}A{S} {S} 0 0 1 0 {y+B-S}Z" fill="{bg}"/>\n'
    o += r("bottom", S, y, 20, B, bg)
    o += f'<path id="{prefix}-bottomright" d="M{S+20} {y}H{W}V{y+B-S}A{S} {S} 0 0 1 {S+20} {y+B}Z" fill="{bg}"/>\n'
    return o + "</g>\n"

def aurorae(d):
    c = P
    mini = lambda g: f'<rect x="9" y="9" width="12" height="2.5" rx="1.25" fill="{g}"/>'
    maxi = lambda g: f'<rect x="10" y="6" width="10" height="8" rx="1.5" fill="none" stroke="{g}" stroke-width="2"/>'
    rest = lambda g: f'<rect x="9" y="8" width="8" height="6" rx="1" fill="none" stroke="{g}" stroke-width="1.8"/><path d="M12 6h8v6" fill="none" stroke="{g}" stroke-width="1.8" stroke-linecap="round"/>'
    clos = lambda g: f'<path d="M11 6l8 8M19 6l-8 8" stroke="{g}" stroke-width="2.2" stroke-linecap="round"/>'
    F = {"close.svg": btn(c["btnBlue"], c["cream"], c["btnBlueHover"], clos),
         "minimize.svg": btn(c["btnYellow"], c["green"], c["btnYellowHover"], mini),
         "maximize.svg": btn(c["btnGreen"], c["green"], c["btnGreenHover"], maxi),
         "restore.svg": btn(c["btnGreen"], c["green"], c["btnGreenHover"], rest),
         "decoration.svg": svg(frame("decoration", c["cream"], c["creamDark"]) + frame("decoration-inactive", c["creamDark"], c["inactiveBg"]), 40, 62)}
    for n, s in F.items():
        open(os.path.join(d, n), "w").write(s)
    rc = os.path.join(d, "ElToClassicrc")
    if os.path.exists(rc):
        t = open(rc).read()
        t = re.sub(r"ActiveTextColor=.*", "ActiveTextColor=" + rgba(c["green"]), t)
        t = re.sub(r"InactiveTextColor=.*", "InactiveTextColor=" + rgba(c["inactiveFg"]), t)
        open(rc, "w").write(t)

def qml(d):
    lines = ["// GENERATED by palette/gen.py from palette/elto-palette.json. Do not edit.",
             "pragma Singleton", "import Quickshell", "import QtQuick", "", "Singleton {"]
    for k, v in P.items():
        lines.append(f'    readonly property color {k}: "{v}"')
    on = bool(M.get("enabled", True))
    lines.append("    // motion (palette/elto-palette.json, section motion). enabled=false zeroes every duration.")
    lines.append(f"    readonly property bool motionEnabled: {str(on).lower()}")
    for k in ("hoverMs", "pressMs", "activeMs", "appearMs", "disappearMs", "popupMs", "popupSlidePx"):
        lines.append(f"    readonly property int {k}: motionEnabled ? {int(M.get(k, 0))} : 0")
    lines.append(f"    readonly property int easing: Easing.{M.get('easing', 'OutCubic')}")
    lines += ["    // roles", "    readonly property color text: green", "    readonly property color panelBg: cream",
              "    readonly property color accent: rust", "}", ""]
    open(os.path.join(d, "ElToPalette.qml"), "w").write("\n".join(lines))

for sub, fn in (("aurorae/ElToClassic", aurorae), ("panel-widgets", qml)):
    d = os.path.join(ROOT, sub)
    if os.path.isdir(d):
        fn(d); print("generated", sub)
    else:
        print("skip", sub)

